const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const assert = require('node:assert/strict');
const compiled = ts.transpile(fs.readFileSync(path.join(__dirname, '../src/indicators.ts'), 'utf8'), { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020 });
const mod = { exports: {} };
new Function('module', 'exports', compiled)(mod, mod.exports);
const { ema, bollinger, fairValueGaps, candleRead, structureLevels, readIndicators } = mod.exports;
const bar = (index, open, high, low, close) => ({ index, open, high, low, close });
const flat = Array.from({ length: 60 }, (_, i) => bar(i, 100, 101, 99, 100));
assert.equal(ema(flat, 20).at(-1).value, 100);
assert.equal(ema(flat, 20).filter(x => x.ready).length, 41);
assert.deepEqual(bollinger(flat).at(-1), { index: 59, mid: 100, upper: 100, lower: 100 });
assert.equal(bollinger(flat.slice(0, 19)).length, 0);
const varied = Array.from({ length: 20 }, (_, i) => bar(i, i + 1, i + 2, i, i + 1));
assert.equal(bollinger(varied)[0].mid, 10.5);
assert(Math.abs(bollinger(varied)[0].upper - (10.5 + 2 * Math.sqrt(33.25))) < 1e-10);
const gap = [bar(1, 100, 102, 99, 101), bar(2, 101, 108, 100, 107), bar(3, 107, 110, 105, 109)];
assert.equal(fairValueGaps(gap).length, 1);
assert.equal(fairValueGaps([...gap, bar(4, 108, 109, 101, 103)]).length, 0, 'filled gaps disappear');
assert.equal(fairValueGaps([gap[0], { ...gap[1], index: 8 }, { ...gap[2], index: 9 }]).length, 0, 'missing buckets are not a fair value gap');
const bearishGap = gap.map(c => bar(c.index, 220 - c.open, 220 - c.low, 220 - c.high, 220 - c.close));
assert.equal(fairValueGaps(bearishGap)[0].side, 'bear');
assert.equal(fairValueGaps([...bearishGap, bar(4, 112, 120, 110, 115)]).length, 0);
assert.equal(candleRead([bar(1, 104, 105, 100, 101), bar(2, 100, 106, 99, 105)]).name, 'Bullish engulfing');
assert.equal(candleRead([bar(1, 101, 105, 100, 104), bar(2, 105, 106, 99, 100)]).name, 'Bearish engulfing');
assert.equal(candleRead([bar(1, 100, 102, 98, 101), bar(2, 100, 110, 90, 100.1)]).name, 'Doji');
assert.equal(candleRead([]), null);
const decline = Array.from({ length: 5 }, (_, i) => bar(i, 110 - i * 2, 111 - i * 2, 108 - i * 2, 109 - i * 2));
assert.equal(candleRead([...decline, bar(5, 100, 101.2, 96, 101)]).name, 'Hammer');
const climb = Array.from({ length: 5 }, (_, i) => bar(i, 90 + i * 2, 92 + i * 2, 89 + i * 2, 91 + i * 2));
assert.equal(candleRead([...climb, bar(5, 100, 104, 98.8, 99)]).name, 'Shooting star');
assert.equal(candleRead([bar(1, 104, 105, 100, 101), bar(5, 100, 106, 99, 105)]), null);
const pivots = [bar(0, 1, 3, 0, 2), bar(1, 2, 4, 1, 3), bar(2, 3, 8, 2, 5), bar(3, 5, 6, 3, 4), bar(4, 4, 5, 2, 3), bar(5, 3, 10, 2, 9)];
assert.equal(structureLevels(pivots).at(-1).label, 'BOS');
assert.equal(structureLevels([...pivots.slice(0, 5), bar(5, 3, 9, 2, 7)]).at(-1).label, 'SWEEP');
assert.equal(structureLevels(pivots.slice(0, 4)).length, 0, 'pivots require two later closed bars');
global.localStorage = { getItem: () => '{broken' };
assert.equal(readIndicators().ema, true);
global.localStorage = { getItem: () => '{"ema":false,"bands":"true","gaps":true}' };
assert.equal(readIndicators().ema, false);
assert.equal(readIndicators().bands, false, 'untrusted stored preferences must be booleans');
console.log('PASS: EMA warm-up, Bollinger variance, bullish/bearish gap fills, missing buckets, candle patterns, confirmed pivots and saved preferences.');
