// Season rank tiers: pure tier maths (no browser). Run: node tests/rank.cjs
const fs = require('node:fs');
const path = require('node:path');
const ts = require('typescript');
const assert = require('node:assert/strict');
const src = fs.readFileSync(path.join(__dirname, '../src/rank.tsx'), 'utf8');
const compiled = ts.transpile(src, { module: ts.ModuleKind.CommonJS, target: ts.ScriptTarget.ES2020, jsx: ts.JsxEmit.ReactJSX });
const mod = { exports: {} };
new Function('module', 'exports', 'require', compiled)(mod, mod.exports, () => ({ jsx: () => null, jsxs: () => null }));
const { rankOf, TIERS } = mod.exports;
const tier = (r) => rankOf(r).tier.id;
assert.deepEqual(TIERS.map(t => t.id), ['iron', 'bronze', 'silver', 'gold', 'platinum', 'diamond', 'legend']);
assert.equal(tier({ return_pct: -6 }), 'iron');
assert.equal(tier({ return_pct: -4 }), 'bronze');
assert.equal(tier({ return_pct: -0.01 }), 'bronze');
assert.equal(tier({ return_pct: 0 }), 'silver');
assert.equal(tier({ return_pct: 3 }), 'gold');
assert.equal(tier({ return_pct: 6.5 }), 'platinum');
assert.equal(tier({ return_pct: 12 }), 'diamond');
assert.equal(tier({ return_pct: 2, funded: true }), 'legend');
assert.equal(tier({ return_pct: 15, status: 'blown' }), 'iron');
assert.equal(tier({ return_pct: NaN }), 'silver');
const g = rankOf({ return_pct: 4.5, qualified: true, trading_days: 7 });
assert.equal(g.next.id, 'platinum'); assert.equal(g.toNext, 1.5); assert.equal(g.progress, 0.5); assert.equal(g.placing, false); assert.equal(g.days, 5);
const d = rankOf({ return_pct: 11, trading_days: 3, qualified: false });
assert.equal(d.next.id, 'legend'); assert.equal(d.toNext, null); assert.equal(d.progress, 0.6); assert.equal(d.placing, true);
assert.equal(rankOf({ return_pct: 1, trading_days: 2 }).placing, true);
assert.equal(rankOf({ return_pct: 1 }).placing, false);
assert.equal(rankOf({ return_pct: 1, funded: true }).next, null);
assert.equal(rankOf({ return_pct: 1, status: 'blown' }).next, null);
assert.ok(rankOf({ return_pct: -10 }).progress >= 0);
console.log('PASS: rank tiers, thresholds, funded Legend, blown Iron, placing, next-tier distance and progress.');
